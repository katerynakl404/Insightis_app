#!/usr/bin/env node
/* Regenerates the index files of BOTH kits from what is on disk.
   Run after adding, renaming or removing a component folder in either of them:

       node devart-ui/tools/build-index.mjs

   insightis-kit/  — the product's React layer over DevartUI (window.InsightisKit)
   review-kit/     — the prototype's review chrome, not product (window.ReviewKit)

   For each kit it writes (never hand-edit the generated blocks):
     <kit>/<kit>.css  — @import of core + every <Name>/<Name>.css
     <kit>/<kit>.js   — loader: core, every <Name>/<Name>.js, and with data-stories on its
                        <script> tag, every *.stories.js
   Idempotent — safe to run from parallel sessions. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));

const KITS = [
  { name: 'insightis-kit', core: 'core/ik-core', what: 'The Insightis custom kit',
    after: 'react.js and _ds_bundle.js', global: 'window.InsightisKit' },
  { name: 'review-kit', core: 'core/rk-core', what: 'The review kit (prototype chrome, not product)',
    after: 'insightis-kit.js', global: 'window.ReviewKit' }
];

const banner = '/* GENERATED by devart-ui/tools/build-index.mjs — do not edit by hand. */\n';

for (const k of KITS) {
  const kit = path.resolve(here, '..', k.name);
  const dirs = fs.readdirSync(kit, { withFileTypes: true })
    .filter(d => d.isDirectory() && d.name !== 'core' && !d.name.startsWith('_'))
    .map(d => d.name)
    .sort((a, b) => a.localeCompare(b));

  const has = (rel) => fs.existsSync(path.join(kit, rel));
  /* ds-bridge/ (TEMPORARY): design-DevartUI components the vendored bundle does not ship yet.
     While the folder exists it loads FIRST, ahead of the product kit; deleting it and re-running
     this script removes it from both indexes. */
  const bridge = k.name === 'insightis-kit' ? ['../ds-bridge/ds-bridge'] : [];
  const css = [...bridge.map(b => `${b}.css`), `${k.core}.css`, ...dirs.map(n => `${n}/${n}.css`)].filter(has);
  const js = [...bridge.map(b => `${b}.js`), `${k.core}.js`, ...dirs.map(n => `${n}/${n}.js`)].filter(has);
  const stories = dirs.map(n => `${n}/${n}.stories.js`).filter(has);

  fs.writeFileSync(path.join(kit, `${k.name}.css`),
    banner + `/* ${k.what} — one stylesheet entry, like ds-bundle/styles.css. */\n` +
    css.map(f => `@import "./${f}";`).join('\n') + '\n');

  fs.writeFileSync(path.join(kit, `${k.name}.js`), banner +
`/* ${k.what} — loader. Include it once, AFTER ${k.after}:
     <script src="…/${k.name}/${k.name}.js"></script>
   It writes one synchronous <script> per component, in order, so everything is registered on
   ${k.global} before the page's own inline script runs. Works on file:// (no fetch).
   Add data-stories to the tag to also load every component's *.stories.js (storybook only). */
(function () {
  var me = document.currentScript;
  var base = me.src.replace(/${k.name}\\.js(\\?.*)?$/, '');
  var files = ${JSON.stringify(js, null, 2).replace(/\n/g, '\n  ')};
  var stories = ${JSON.stringify(stories, null, 2).replace(/\n/g, '\n  ')};
  if (me.hasAttribute('data-stories')) files = files.concat(stories);
  for (var i = 0; i < files.length; i++) document.write('<script src="' + base + files[i] + '"><\\/script>');
})();
`);

  console.log(`${k.name}: ${dirs.length} components, ${css.length} css, ${js.length} js, ${stories.length} stories`);
}
